"""Tokenise every sentence and every word type with every tokenizer.

Outputs (gitignored, regenerated by `make measure`):
  data/token_counts.parquet  one row per (tokenizer, language, sentence)
  data/word_counts.parquet   one row per (tokenizer, language, word type)
results/tokenizers.csv records what was actually loaded (vocab size, status).
"""

from __future__ import annotations

import time
import traceback
from collections import Counter

import pandas as pd

from token_tax.config import Config, TokenizerSpec
from token_tax.data import load_sentences
from token_tax.metrics import core_word, utf8_len, whitespace_words
from token_tax.tokenization import Encoder, load_encoder


def sentence_stats(sentences: pd.DataFrame, codes: list[str]) -> pd.DataFrame:
    """Tokenizer-independent size of every sentence: characters, UTF-8 bytes, words."""
    rows = []
    for code in codes:
        for sid, text in zip(sentences["sentence_id"], sentences[code], strict=True):
            rows.append(
                {
                    "sentence_id": int(sid),
                    "lang": code,
                    "chars": len(text),
                    "bytes": utf8_len(text),
                    "words": len(whitespace_words(text)),
                }
            )
    return pd.DataFrame(rows)


def _count_sentences(
    enc: Encoder, spec: TokenizerSpec, sentences: pd.DataFrame, codes: list[str]
) -> pd.DataFrame:
    unk = enc.unk_id()
    rows = []
    for code in codes:
        texts = sentences[code].tolist()
        for sid, ids in zip(sentences["sentence_id"], enc.encode_batch(texts), strict=True):
            rows.append(
                {
                    "tokenizer": spec.key,
                    "lang": code,
                    "sentence_id": int(sid),
                    "tokens": len(ids),
                    "unk": sum(1 for i in ids if i == unk) if unk is not None else 0,
                }
            )
    return pd.DataFrame(rows)


def _count_words(
    enc: Encoder, spec: TokenizerSpec, sentences: pd.DataFrame, codes: list[str]
) -> pd.DataFrame:
    """Token count of every word type encoded on its own (with the word-boundary prefix).

    `kind="core"` rows are punctuation-stripped words used for vocabulary coverage;
    `kind="raw"` rows are whitespace words as they appear, used only for a sanity check
    that isolated-word counts add up to roughly the sentence-level counts.
    """
    frames = []
    for code in codes:
        raw_words: Counter[str] = Counter()
        core_words: Counter[str] = Counter()
        for text in sentences[code]:
            for word in whitespace_words(text):
                raw_words[word] += 1
                core = core_word(word)
                if core:
                    core_words[core] += 1
        for kind, counter in (("raw", raw_words), ("core", core_words)):
            types = sorted(counter)
            ids = enc.encode_batch([spec.word_prefix + w for w in types])
            frames.append(
                pd.DataFrame(
                    {
                        "tokenizer": spec.key,
                        "lang": code,
                        "kind": kind,
                        "word": types,
                        "freq": [counter[w] for w in types],
                        "tokens": [len(x) for x in ids],
                    }
                )
            )
    return pd.concat(frames, ignore_index=True)


def run(cfg: Config) -> None:
    sentences = load_sentences(cfg)
    codes = [lang.code for lang in cfg.languages]
    out_dir = cfg.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    sentence_stats(sentences, codes).to_parquet(
        cfg.root / "data" / "sentence_stats.parquet", index=False
    )

    counts: list[pd.DataFrame] = []
    words: list[pd.DataFrame] = []
    status: list[dict[str, object]] = []
    for spec in cfg.tokenizers:
        start = time.perf_counter()
        try:
            enc = load_encoder(spec)
            counts.append(_count_sentences(enc, spec, sentences, codes))
            words.append(_count_words(enc, spec, sentences, codes))
        except Exception as exc:  # report and continue; failures are listed in the README
            traceback.print_exc()
            status.append(
                {
                    "key": spec.key,
                    "label": spec.label,
                    "source": spec.source,
                    "vocab_size": None,
                    "status": f"failed: {type(exc).__name__}: {exc}",
                }
            )
            continue
        elapsed = time.perf_counter() - start
        status.append(
            {
                "key": spec.key,
                "label": spec.label,
                "source": spec.source,
                "vocab_size": enc.vocab_size(),
                "status": "ok",
            }
        )
        print(f"{spec.key:<10} vocab={enc.vocab_size():>7}  {elapsed:5.1f}s")

    if not counts:
        raise RuntimeError("no tokenizer could be loaded")
    pd.concat(counts, ignore_index=True).to_parquet(cfg.counts_path, index=False)
    pd.concat(words, ignore_index=True).to_parquet(cfg.words_path, index=False)
    pd.DataFrame(status).to_csv(out_dir / "tokenizers.csv", index=False)
